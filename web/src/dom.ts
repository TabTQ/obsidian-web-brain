/** Render text with [start,end) highlight ranges. */
export function highlightRanges(text: string, ranges: [number, number][]): Node {
  const frag = document.createDocumentFragment();
  let i = 0;
  for (const [a, b] of ranges) {
    if (a > i) frag.append(text.slice(i, a));
    frag.append(h("mark", { class: "hl" }, text.slice(a, b)));
    i = b;
  }
  if (i < text.length) frag.append(text.slice(i));
  return frag;
}

export function fileUrl(path: string, source = "") {
  return `/api/v1/file?path=${encodeURIComponent(path)}${source ? `&source=${encodeURIComponent(source)}` : ""}`;
}
